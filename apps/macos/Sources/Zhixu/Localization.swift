import Foundation

/// Stable for the lifetime of the process so language changes never recreate
/// an editor or discard an in-progress merge draft.
enum AppLanguage {
    static let preferenceKey = "appLanguage"
    static func detect(_ preferredLanguages: [String]) -> String {
        let primary = preferredLanguages.first?.lowercased().replacingOccurrences(of: "_", with: "-") ?? "en"
        return primary == "zh" || primary.hasPrefix("zh-") ? "zh-Hans" : "en"
    }
    static func resolve(defaults: UserDefaults, preferredLanguages: [String]) -> String {
        if let saved = defaults.string(forKey: preferenceKey), ["zh-Hans", "en"].contains(saved) { return saved }
        return detect(preferredLanguages)
    }
    static let current: String = {
        let defaults = UserDefaults.standard
        let value = resolve(defaults: defaults, preferredLanguages: Locale.preferredLanguages)
        defaults.set(value, forKey: preferenceKey)
        return value
    }()
    static func bootstrap() {
        // App-domain override only; never changes the user's system language.
        UserDefaults.standard.set([current], forKey: "AppleLanguages")
    }
    static func text(_ key: String, arguments: [String] = [], language: String = current) -> String {
        let template = language == "en" ? english[key] ?? key : key
        // A single pass preserves placeholders appearing in user-provided values.
        var result = "", index = template.startIndex
        while index < template.endIndex {
            if template[index] == "{", let end = template[index...].firstIndex(of: "}"),
               let number = Int(template[template.index(after: index)..<end]), arguments.indices.contains(number) {
                result += arguments[number]; index = template.index(after: end)
            } else { result.append(template[index]); index = template.index(after: index) }
        }
        return result
    }
